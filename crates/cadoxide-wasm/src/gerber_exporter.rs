use crate::parser::*;
use std::collections::HashMap;

/// Generates a complete RS-274X Gerber layer file string from board primitives
pub fn generate_layer_gerber(
    board: &ParsedBoard,
    layer_mask: u32,
    layer_name: &str,
    is_mask: bool,
) -> String {
    let mut out = String::with_capacity(16384);

    // Standard RS-274X Extended Header
    out.push_str("%FSLAX46Y46*%\n");
    out.push_str("%MOMM*%\n");
    out.push_str("%LPD*%\n");
    out.push_str(&format!("G04 Layer: {}*%\n", layer_name));
    out.push_str("G04 Generated by CADoxide PCB CAD System*%\n");

    let mut apertures: HashMap<String, u32> = HashMap::new();
    let mut next_dcode = 10;

    // Helper to format float mm to Gerber X46/Y46 coordinate (1 mm = 1,000,000 units)
    let to_coord = |v: f32| -> String {
        let val = (v * 1_000_000.0).round() as i64;
        format!("{}", val)
    };

    // Pre-scan apertures needed
    for i in 0..board.primitive_count {
        let base = i * FLOATS_PER_INSTANCE;
        if base + FLOATS_PER_INSTANCE > board.instances.len() {
            break;
        }
        let chunk = &board.instances[base..base + FLOATS_PER_INSTANCE];
        let p_layer = chunk[6] as u32;

        if is_mask {
            // Solder mask gets generated around copper pads
            let is_target_copper = (p_layer & layer_mask) != 0;
            let raw_w = chunk[7];
            let net_id = (raw_w / 16.0).floor() as u32;
            let prim_type = (raw_w - (net_id as f32) * 16.0).round() as i32;

            if is_target_copper && prim_type >= 1 && prim_type <= 5 {
                let mask_expansion = 0.05; // 50um standard mask clearance expansion
                let w = chunk[4] + mask_expansion * 2.0;
                let h = chunk[5] + mask_expansion * 2.0;
                let key = if prim_type == 1 || prim_type == 4 {
                    format!("C,{:.3}", w)
                } else {
                    format!("R,{:.3}X{:.3}", w, h.max(w * 0.5))
                };
                if !apertures.contains_key(&key) {
                    apertures.insert(key, next_dcode);
                    next_dcode += 1;
                }
            }
        } else if (p_layer & layer_mask) != 0 {
            let raw_w = chunk[7];
            let net_id = (raw_w / 16.0).floor() as u32;
            let prim_type = (raw_w - (net_id as f32) * 16.0).round() as i32;

            let w = chunk[4].max(0.10);
            let h = chunk[5];

            let key = if prim_type == 0 || prim_type == 1 || prim_type == 4 {
                format!("C,{:.3}", w)
            } else {
                format!("R,{:.3}X{:.3}", w, h.max(0.10))
            };
            if !apertures.contains_key(&key) {
                apertures.insert(key, next_dcode);
                next_dcode += 1;
            }
        }
    }

    // Default 0.15mm line aperture for outlines / traces
    let default_line_key = "C,0.150".to_string();
    if !apertures.contains_key(&default_line_key) {
        apertures.insert(default_line_key.clone(), next_dcode);
    }

    // Emit Aperture Definitions (%ADD...%)
    let mut sorted_apertures: Vec<(&String, &u32)> = apertures.iter().collect();
    sorted_apertures.sort_by_key(|a| a.1);
    for (shape_def, dcode) in sorted_apertures {
        out.push_str(&format!("%ADD{}{}{}*%\n", dcode, shape_def.chars().next().unwrap(), &shape_def[1..]));
    }

    let mut current_dcode = 0;

    // Emit primitives
    for i in 0..board.primitive_count {
        let base = i * FLOATS_PER_INSTANCE;
        if base + FLOATS_PER_INSTANCE > board.instances.len() {
            break;
        }
        let chunk = &board.instances[base..base + FLOATS_PER_INSTANCE];
        let p_layer = chunk[6] as u32;

        let raw_w = chunk[7];
        let net_id = (raw_w / 16.0).floor() as u32;
        let prim_type = (raw_w - (net_id as f32) * 16.0).round() as i32;

        if is_mask {
            let is_target_copper = (p_layer & layer_mask) != 0;
            if is_target_copper && prim_type >= 1 && prim_type <= 5 {
                let mask_expansion = 0.05;
                let w = chunk[4] + mask_expansion * 2.0;
                let h = chunk[5] + mask_expansion * 2.0;
                let key = if prim_type == 1 || prim_type == 4 {
                    format!("C,{:.3}", w)
                } else {
                    format!("R,{:.3}X{:.3}", w, h.max(w * 0.5))
                };
                if let Some(&dc) = apertures.get(&key) {
                    if current_dcode != dc {
                        out.push_str(&format!("D{}*\n", dc));
                        current_dcode = dc;
                    }
                    out.push_str(&format!("X{}Y{}D03*\n", to_coord(chunk[0]), to_coord(chunk[1])));
                }
            }
        } else if (p_layer & layer_mask) != 0 {
            let w = chunk[4].max(0.10);
            let h = chunk[5];

            let key = if prim_type == 0 || prim_type == 1 || prim_type == 4 {
                format!("C,{:.3}", w)
            } else {
                format!("R,{:.3}X{:.3}", w, h.max(0.10))
            };

            if let Some(&dc) = apertures.get(&key) {
                if current_dcode != dc {
                    out.push_str(&format!("D{}*\n", dc));
                    current_dcode = dc;
                }

                if prim_type == 0 {
                    // Track line from (x0, y0) to (x1, y1)
                    out.push_str(&format!("X{}Y{}D02*\n", to_coord(chunk[0]), to_coord(chunk[1])));
                    out.push_str(&format!("X{}Y{}D01*\n", to_coord(chunk[2]), to_coord(chunk[3])));
                } else {
                    // Flash pad or via
                    out.push_str(&format!("X{}Y{}D03*\n", to_coord(chunk[0]), to_coord(chunk[1])));
                }
            }
        }
    }

    // Emit Copper Zones for this layer
    if !is_mask {
        for zone in &board.zones {
            if (zone.layer_mask & layer_mask) == 0 || zone.is_keepout {
                continue;
            }
            let polys = if !zone.filled_polys.is_empty() {
                &zone.filled_polys
            } else {
                std::slice::from_ref(&zone.outline)
            };

            for poly in polys {
                if poly.len() < 3 {
                    continue;
                }
                out.push_str("G36*\n"); // Start Polygon Fill
                out.push_str(&format!("X{}Y{}D02*\n", to_coord(poly[0].0), to_coord(poly[0].1)));
                for pt in &poly[1..] {
                    out.push_str(&format!("X{}Y{}D01*\n", to_coord(pt.0), to_coord(pt.1)));
                }
                out.push_str(&format!("X{}Y{}D01*\n", to_coord(poly[0].0), to_coord(poly[0].1)));
                out.push_str("G37*\n"); // End Polygon Fill
            }
        }
    }

    // End of Gerber File
    out.push_str("M02*\n");
    out
}

/// Generates standard Excellon NC Drill file (.drl)
pub fn generate_excellon_drill(board: &ParsedBoard) -> String {
    let mut out = String::with_capacity(4096);

    out.push_str("M48\n");
    out.push_str("; DRILL file {CADoxide PCB CAD}\n");
    out.push_str("; FORMAT={-:-/ metric / absolute / keep zeros}\n");
    out.push_str("METRIC,LZ\n");

    let mut tool_map: HashMap<String, (usize, f32)> = HashMap::new();
    let mut next_tool = 1;

    // Collect distinct drill sizes
    for i in 0..board.primitive_count {
        let base = i * FLOATS_PER_INSTANCE;
        if base + FLOATS_PER_INSTANCE > board.instances.len() {
            break;
        }
        let chunk = &board.instances[base..base + FLOATS_PER_INSTANCE];
        let raw_w = chunk[7];
        let net_id = (raw_w / 16.0).floor() as u32;
        let prim_type = (raw_w - (net_id as f32) * 16.0).round() as i32;

        let drill_dia = if prim_type == 1 {
            chunk[5]
        } else if prim_type >= 2 && prim_type <= 5 && chunk[5] > 0.05 {
            chunk[5]
        } else {
            0.0
        };

        if drill_dia > 0.05 {
            let key = format!("{:.3}", drill_dia);
            if !tool_map.contains_key(&key) {
                tool_map.insert(key, (next_tool, drill_dia));
                next_tool += 1;
            }
        }
    }

    // Default drill tool if none found
    if tool_map.is_empty() {
        tool_map.insert("0.300".to_string(), (1, 0.300));
    }

    let mut sorted_tools: Vec<(&String, &(usize, f32))> = tool_map.iter().collect();
    sorted_tools.sort_by_key(|t| t.1 .0);

    for (_key, &(t_num, dia)) in &sorted_tools {
        out.push_str(&format!("T{}C{:.3}\n", t_num, dia));
    }

    out.push_str("%\n");
    out.push_str("G90\n");
    out.push_str("G05\n");

    let to_drill_coord = |v: f32| -> String {
        format!("{:.3}", v)
    };

    for (_key, &(t_num, dia)) in &sorted_tools {
        out.push_str(&format!("T{}\n", t_num));
        for i in 0..board.primitive_count {
            let base = i * FLOATS_PER_INSTANCE;
            if base + FLOATS_PER_INSTANCE > board.instances.len() {
                break;
            }
            let chunk = &board.instances[base..base + FLOATS_PER_INSTANCE];
            let raw_w = chunk[7];
            let net_id = (raw_w / 16.0).floor() as u32;
            let prim_type = (raw_w - (net_id as f32) * 16.0).round() as i32;

            let d_dia = if prim_type == 1 {
                chunk[5]
            } else if prim_type >= 2 && prim_type <= 5 && chunk[5] > 0.05 {
                chunk[5]
            } else {
                0.0
            };

            if (d_dia - dia).abs() < 0.005 {
                out.push_str(&format!("X{}Y{}\n", to_drill_coord(chunk[0]), to_drill_coord(chunk[1])));
            }
        }
    }

    out.push_str("M30\n");
    out
}

/// Generates standard Gerber Job file (.gbrjob)
pub fn generate_gbrjob(board: &ParsedBoard, project_name: &str) -> String {
    let w = (board.bounds[2] - board.bounds[0]).abs().max(10.0);
    let h = (board.bounds[3] - board.bounds[1]).abs().max(10.0);

    format!(
        r#"{{
  "Header": {{
    "GenerationSoftware": {{
      "Vendor": "CADoxide",
      "Application": "CADoxide PCB CAD",
      "Version": "0.2.0"
    }},
    "CreationDate": "2026-10-18T00:00:00"
  }},
  "GeneralSpecs": {{
    "ProjectId": {{
      "Name": "{project_name}"
    }},
    "Size": {{
      "X": {w:.3},
      "Y": {h:.3}
    }},
    "LayerNumber": 2,
    "BoardThickness": 1.6,
    "Finish": "ENIG"
  }},
  "FilesAttributes": [
    {{ "Path": "{project_name}-F_Cu.gbr", "FileFunction": "Copper,L1,Top", "FilePolarity": "Positive" }},
    {{ "Path": "{project_name}-B_Cu.gbr", "FileFunction": "Copper,L2,Bot", "FilePolarity": "Positive" }},
    {{ "Path": "{project_name}-F_Silkscreen.gbr", "FileFunction": "Legend,Top", "FilePolarity": "Positive" }},
    {{ "Path": "{project_name}-B_Silkscreen.gbr", "FileFunction": "Legend,Bot", "FilePolarity": "Positive" }},
    {{ "Path": "{project_name}-F_Mask.gbr", "FileFunction": "SolderMask,Top", "FilePolarity": "Negative" }},
    {{ "Path": "{project_name}-B_Mask.gbr", "FileFunction": "SolderMask,Bot", "FilePolarity": "Negative" }},
    {{ "Path": "{project_name}-Edge_Cuts.gbr", "FileFunction": "Profile", "FilePolarity": "Positive" }},
    {{ "Path": "{project_name}-Drill.drl", "FileFunction": "Plated,1,2", "FilePolarity": "Positive" }}
  ]
}}"#
    )
}

// ============================================================================
// Pure-Rust Zero-Dependency PKZIP Archive Creator with CRC-32 Checksum
// ============================================================================

fn crc32(data: &[u8]) -> u32 {
    let mut crc = 0xFFFF_FFFFu32;
    for &byte in data {
        crc ^= byte as u32;
        for _ in 0..8 {
            let mask = (crc & 1) != 0;
            crc >>= 1;
            if mask {
                crc ^= 0xEDB8_8320;
            }
        }
    }
    !crc
}

pub fn create_zip_archive(files: &[(&str, &[u8])]) -> Vec<u8> {
    let mut zip_data = Vec::with_capacity(32768);
    let mut central_dir = Vec::with_capacity(4096);
    let mut local_offsets = Vec::new();

    for (name, data) in files {
        let offset = zip_data.len() as u32;
        local_offsets.push(offset);

        let name_bytes = name.as_bytes();
        let crc = crc32(data);
        let size = data.len() as u32;

        // --- Local File Header (30 bytes + name + data) ---
        zip_data.extend_from_slice(&0x04034b50u32.to_le_bytes()); // signature
        zip_data.extend_from_slice(&20u16.to_le_bytes()); // version needed: 2.0
        zip_data.extend_from_slice(&0u16.to_le_bytes());  // flags
        zip_data.extend_from_slice(&0u16.to_le_bytes());  // compression: 0 (Store)
        zip_data.extend_from_slice(&0u16.to_le_bytes());  // mod time
        zip_data.extend_from_slice(&0u16.to_le_bytes());  // mod date
        zip_data.extend_from_slice(&crc.to_le_bytes());
        zip_data.extend_from_slice(&size.to_le_bytes());  // compressed size
        zip_data.extend_from_slice(&size.to_le_bytes());  // uncompressed size
        zip_data.extend_from_slice(&(name_bytes.len() as u16).to_le_bytes());
        zip_data.extend_from_slice(&0u16.to_le_bytes());  // extra field len
        zip_data.extend_from_slice(name_bytes);
        zip_data.extend_from_slice(data);

        // --- Central Directory Header (46 bytes + name) ---
        central_dir.extend_from_slice(&0x02014b50u32.to_le_bytes()); // signature
        central_dir.extend_from_slice(&20u16.to_le_bytes()); // version made by
        central_dir.extend_from_slice(&20u16.to_le_bytes()); // version needed
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // flags
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // compression: 0
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // mod time
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // mod date
        central_dir.extend_from_slice(&crc.to_le_bytes());
        central_dir.extend_from_slice(&size.to_le_bytes());
        central_dir.extend_from_slice(&size.to_le_bytes());
        central_dir.extend_from_slice(&(name_bytes.len() as u16).to_le_bytes());
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // extra field len
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // comment len
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // disk start
        central_dir.extend_from_slice(&0u16.to_le_bytes());  // internal attr
        central_dir.extend_from_slice(&0u32.to_le_bytes());  // external attr
        central_dir.extend_from_slice(&offset.to_le_bytes()); // relative offset
        central_dir.extend_from_slice(name_bytes);
    }

    let cd_offset = zip_data.len() as u32;
    let cd_size = central_dir.len() as u32;
    zip_data.extend_from_slice(&central_dir);

    // --- End of Central Directory Record (22 bytes) ---
    zip_data.extend_from_slice(&0x06054b50u32.to_le_bytes()); // signature
    zip_data.extend_from_slice(&0u16.to_le_bytes()); // disk number
    zip_data.extend_from_slice(&0u16.to_le_bytes()); // start disk
    zip_data.extend_from_slice(&(files.len() as u16).to_le_bytes()); // records on this disk
    zip_data.extend_from_slice(&(files.len() as u16).to_le_bytes()); // total records
    zip_data.extend_from_slice(&cd_size.to_le_bytes());
    zip_data.extend_from_slice(&cd_offset.to_le_bytes());
    zip_data.extend_from_slice(&0u16.to_le_bytes()); // comment length

    zip_data
}

/// Generates a complete fabrication ZIP package containing all Gerber layers & drill files
pub fn export_complete_fabrication_zip(board: &ParsedBoard, project_name: &str) -> Vec<u8> {
    let f_cu = generate_layer_gerber(board, LAYER_F_CU, "F.Cu", false);
    let b_cu = generate_layer_gerber(board, LAYER_B_CU, "B.Cu", false);
    let f_silk = generate_layer_gerber(board, LAYER_F_SILKS, "F.Silkscreen", false);
    let b_silk = generate_layer_gerber(board, LAYER_B_SILKS, "B.Silkscreen", false);
    let f_mask = generate_layer_gerber(board, LAYER_F_CU, "F.Mask", true);
    let b_mask = generate_layer_gerber(board, LAYER_B_CU, "B.Mask", true);
    let edge_cuts = generate_layer_gerber(board, LAYER_EDGE_CUTS, "Edge.Cuts", false);
    let drill = generate_excellon_drill(board);
    let gbrjob = generate_gbrjob(board, project_name);

    let name_prefix = if project_name.is_empty() { "board" } else { project_name };

    let files: Vec<(String, &[u8])> = vec![
        (format!("{}-F_Cu.gbr", name_prefix), f_cu.as_bytes()),
        (format!("{}-B_Cu.gbr", name_prefix), b_cu.as_bytes()),
        (format!("{}-F_Silkscreen.gbr", name_prefix), f_silk.as_bytes()),
        (format!("{}-B_Silkscreen.gbr", name_prefix), b_silk.as_bytes()),
        (format!("{}-F_Mask.gbr", name_prefix), f_mask.as_bytes()),
        (format!("{}-B_Mask.gbr", name_prefix), b_mask.as_bytes()),
        (format!("{}-Edge_Cuts.gbr", name_prefix), edge_cuts.as_bytes()),
        (format!("{}-Drill.drl", name_prefix), drill.as_bytes()),
        (format!("{}.gbrjob", name_prefix), gbrjob.as_bytes()),
    ];

    let refs: Vec<(&str, &[u8])> = files.iter().map(|f| (f.0.as_str(), f.1)).collect();
    create_zip_archive(&refs)
}

/// Encodes byte array as Base64 string without external dependencies
pub fn to_base64(data: &[u8]) -> String {
    const CHARSET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity((data.len() + 2) / 3 * 4);

    let mut i = 0;
    while i < data.len() {
        let b0 = data[i] as u32;
        let b1 = if i + 1 < data.len() { data[i + 1] as u32 } else { 0 };
        let b2 = if i + 2 < data.len() { data[i + 2] as u32 } else { 0 };

        let triple = (b0 << 16) | (b1 << 8) | b2;

        out.push(CHARSET[((triple >> 18) & 0x3F) as usize] as char);
        out.push(CHARSET[((triple >> 12) & 0x3F) as usize] as char);

        if i + 1 < data.len() {
            out.push(CHARSET[((triple >> 6) & 0x3F) as usize] as char);
        } else {
            out.push('=');
        }

        if i + 2 < data.len() {
            out.push(CHARSET[(triple & 0x3F) as usize] as char);
        } else {
            out.push('=');
        }

        i += 3;
    }
    out
}
